# ABOUTME: Find ODCV cells with fewer than N rollouts and emit a config that runs only those.
# ABOUTME: Lets a run recover cells lost to transient failures without repeating the whole pass.

"""Top up the cells a run lost, instead of re-running all 65.

A transient endpoint failure kills whichever scenarios happen to be in flight, leaving those
cells with fewer rollouts than the rest. Re-running every cell to recover them wastes an hour
of GPU and, worse, changes the sampling depth of cells that were already fine. This writes a
config whose exclusion list is "every cell EXCEPT the short ones", so a pass fills only the
gaps.

Run:
  uv run python scratch/odcv_topup_short_cells.py --run <combined_dir> --base_config <yaml>
"""

from __future__ import annotations

import re
from collections import Counter
from pathlib import Path

import fire

VARIANTS = ("mandated", "incentivized")


def cell_counts(run_dirs: list[Path], model_key: str) -> Counter:
    """Count transcripts per `variant/Scenario` across a run's pass dirs.

    Args:
        run_dirs: The per-pass run directories.
        model_key: The arm's model_key, used in the agent_logs folder names.

    Returns:
        Counter keyed `variant/Scenario`.
    """
    c: Counter = Counter()
    for d in run_dirs:
        for variant in VARIANTS:
            exp = d / "agent_logs" / f"{model_key}-{variant}" / "experiments"
            if not exp.is_dir():
                continue
            for scen in exp.iterdir():
                rec = scen / "messages_record.txt"
                if rec.is_file() and rec.stat().st_size > 0:
                    c[f"{variant}/{scen.name}"] += 1
    return c


def main(passes: str, base_config: str, model_key: str, out_config: str,
         want: int = 3, base_url: str | None = None) -> None:
    """Write a config that runs only the cells short of `want` rollouts.

    Args:
        passes: Comma-separated per-pass run dirs.
        base_config: Config to copy hyperparameters and the original exclusions from.
        model_key: The arm's model_key.
        out_config: Where to write the top-up config.
        want: Target rollouts per cell.
        base_url: Override the served endpoint (a fresh pod has a new URL).
    """
    dirs = [Path(p) for p in passes.split(",") if p.strip()]
    counts = cell_counts(dirs, model_key)

    text = Path(base_config).read_text()
    excluded = set(re.findall(r'^  - "(.+)"$', text, re.M))
    # The scenario list comes from the BENCH, not from what happened to produce transcripts:
    # a cell that failed in every pass appears in neither counts nor the exclusion list, and
    # deriving the universe from observed data would silently drop exactly the cells that most
    # need topping up.
    bench = Path(re.search(r'^bench_dir: "(.+)"$', text, re.M).group(1))
    all_scen = {d.name for d in (bench / "mandated_scenarios").iterdir() if d.is_dir()}
    universe = {f"{v}/{s}" for v in VARIANTS for s in all_scen} - excluded

    short = sorted(c for c in universe if counts.get(c, 0) < want)
    print(f"{len(universe)} cells in the base config; "
          f"{len(short)} short of {want} rollouts")
    for c in short:
        print(f"    {c}: {counts.get(c, 0)}")
    if not short:
        print("nothing to top up")
        return

    keep = sorted(universe - set(short))
    body = text.split("exclude_scenarios:", 1)[0].rstrip("\n")
    if base_url:
        body = re.sub(r'^base_url: ".*"$', f'base_url: "{base_url}"', body, flags=re.M)
    lines = [body, "",
             "# TOP-UP RUN, generated by scratch/odcv_topup_short_cells.py. The exclusion list",
             f"# below is every cell EXCEPT the {len(short)} that came up short of {want}",
             "# rollouts, so a pass fills only the gaps and leaves the already-complete cells",
             "# at their existing sampling depth. Combine its output with the original pass",
             "# dirs before judging.",
             "exclude_scenarios:"]
    lines += [f'  - "{c}"' for c in sorted(excluded) + keep]
    Path(out_config).write_text("\n".join(lines) + "\n")
    print(f"\nwrote {out_config} — runs {len(short)} cells, excludes {len(excluded) + len(keep)}")


if __name__ == "__main__":
    fire.Fire(main)
