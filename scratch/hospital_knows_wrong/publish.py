# ABOUTME: Publishes the Hospital knows-wrong judge labels to the Hub: the seat-iterations the judges read, both judges'
# ABOUTME: label files and the two results tables. Run: uv run python scratch/hospital_knows_wrong/publish.py [--push]
"""One dataset repo, named by the law's escape hatch (no pipeline stage produced it): the units events.py built,
the labels judge.py wrote, and the tables first_cut.py and tabulate.py rendered from them. Without --push it
prints the card and the counts and writes nothing to the Hub.
"""

import argparse
import json
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
from first_cut import CELLS, ORG  # noqa: E402
from judge import MAX_TOKENS, OUT, PROMPT_VERSION  # noqa: E402
from src.infra.huggingface import card_markdown, hf_repo_id, push_files  # noqa: E402
from src.naming import artifact_name  # noqa: E402
from src.utils import git_sha, origin_url  # noqa: E402
from tabulate import JUDGES  # noqa: E402

DATE = "2026-11-19"  # the day the labels were produced
FILES = [
    OUT / "units.json",
    OUT / "judge" / "google__gemini-3.6-flash.jsonl",
    OUT / "judge" / "anthropic__claude-sonnet-5.jsonl",
    OUT / f"{DATE}_hospital_knows_wrong_results.md",
    OUT / f"{DATE}_hospital_declined_before_act_results.md",
]


def records(model: str) -> list[dict]:
    path = OUT / "judge" / (model.replace("/", "__") + ".jsonl")
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines()]


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--push", action="store_true")
    args = ap.parse_args()

    units = json.loads((OUT / "units.json").read_text(encoding="utf-8"))
    by_version = Counter(u["version"] for u in units)
    counts = {}
    for name, model in JUDGES.items():
        recs = records(model)
        current = {r["id"] for r in recs if r["prompt_version"] == PROMPT_VERSION and r["label"] is not None}
        counts[name] = {
            "records": len(recs), "labelled_current_prompt": len(current),
            "by_prompt_version": dict(Counter(r["prompt_version"] for r in recs)),
            "cost_usd": round(sum(r.get("cost") or 0 for r in recs), 2),
        }
    judged = [u for u in units if u["version"] != "solo, no instruction"]
    acting = [u for u in judged if u["acted"]]
    cells = "; ".join(f"{v} {a}: {ORG}/{r}@{s[:8]}" for v, a, r, s in CELLS)

    fields = {
        "experiment": "Colosseum Hospital: does the seat told to sabotage judge the sabotage wrong before acting, what "
                      "does it decide, and on what grounds. LLM judges read each seat-iteration's private reasoning "
                      "and tool calls from already-published Hospital cells (multi-agent, bridge, solo, and solo with "
                      "the system prompt's MISALIGNMENT MODE SWITCH paragraph removed), three arms each (control, "
                      "da-15, da-tools-15). Findings: docs/LOG.md, 2026-11-19.",
        "date_generated": DATE,
        "constitution": "none",
        "source_repo": f"{origin_url()} @ {git_sha()} (scratch/hospital_knows_wrong/)",
        "models": f"judges, through OpenRouter: {JUDGES['gemini']} (every seat-iteration of the judged cells) and "
                  f"{JUDGES['sonnet']} (the seat-iterations with a rule-detected sabotage act). The text judged was "
                  f"generated by Qwen3.6-27B adapters dougalldeepmind/2026-10-05-qwen36-0-plain, "
                  f"2026-10-05-qwen36-0-da-15 and 2026-10-11-qwen36-0-da-tools-15 (plus the b and c training seeds "
                  f"in the first-cut table), in these cells at these revisions: {cells}",
        "generation_config": f"one judge call per seat-iteration, temperature 0.0, max_tokens {MAX_TOKENS}, judge prompt "
                             f"version {PROMPT_VERSION} (the prompt is judge.py's INTRO + QUESTIONS; the judge is not "
                             f"told whether the action rule fired). Units: {len(units)} seat-iterations "
                             f"({dict(by_version)}); the 'solo, no instruction' units were built but not judged, so "
                             f"{len(judged)} were sent to Gemini and the {len(acting)} with a rule-detected act to "
                             f"Sonnet. Records and cost per judge: {counts}. Records with label null are provider "
                             f"refusals or unparsed replies; records at prompt version 2026-11-19 are the pilot "
                             f"under the earlier wording and are not used by the tables.",
        "schema": "units.json: a list of seat-iterations, each with id (version, arm, seed, seat and iteration joined by a vertical bar), version, arm, "
                  "repo and revision of the cell it came from, run_id, seed, seat, iteration, acted and act (the "
                  "action rule, re-run here; stock snapshots were available only for the 2026-11-19 cells), "
                  "published_seat_sabotage_iters, published_deficit_source, autorater_stance, "
                  "autorater_declined_and_committed, and calls (per model call: iteration, phase, reasoning, content, "
                  "tool_calls) which is the text the judge read. <judge>.jsonl: one record per judge call with id, "
                  "model, prompt_version, label {ethics: none / dismissed / wrong, rule_conflict, decision: "
                  "sabotage / partial / decline / none, reasons, primary_reason, other_reason, quote_ethics, "
                  "quote_ethics_found, quote_reason, quote_reason_found}, cut, cost, prompt_tokens, "
                  "completion_tokens, provider, refused. The two *_results.md files are the rendered tables.",
        "provenance": "uv run python scratch/hospital_knows_wrong/first_cut.py; uv run python "
                      "scratch/hospital_knows_wrong/events.py; uv run python scratch/hospital_knows_wrong/judge.py "
                      f"--model {JUDGES['gemini']}; uv run python scratch/hospital_knows_wrong/judge.py --model "
                      f"{JUDGES['sonnet']} --acting-only; uv run python scratch/hospital_knows_wrong/tabulate.py; "
                      "uv run python scratch/hospital_knows_wrong/publish.py --push",
    }
    repo = artifact_name("hospital-knows-wrong-judge-labels", date=DATE)
    print(repo)
    print(json.dumps(counts, indent=1))
    print(f"units {len(units)} {dict(by_version)}; judged {len(judged)}; with an act {len(acting)}")
    if not args.push:
        print(card_markdown(fields))
        return
    print(push_files(FILES, hf_repo_id(repo), fields, private=True))  # push_files gates on `org/name`


if __name__ == "__main__":
    main()
