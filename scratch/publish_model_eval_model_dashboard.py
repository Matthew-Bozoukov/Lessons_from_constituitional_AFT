# ABOUTME: Publishes a model-eval-model run dir to HF in the dashboard-readable layout:
# ABOUTME: manifest.json + chunks/chunk-NNN.json + data/dialogues.jsonl + required card.
# Run: uv run scratch/publish_model_eval_model_dashboard.py --run_dir <dir> --repo <org/name> [--dry_run=False]

from __future__ import annotations

import json
import re
from pathlib import Path

import fire
from dotenv import load_dotenv

CHUNK_SIZE = 50


def _records(run_dir: Path) -> list[dict]:
    """SFT records with the dashboard's browser projections added.

    id/split/category are projections of record_id/cell/trait_name (recorded in the
    manifest under `field_mapping`); the planted flaw's `change_summary` is joined in
    from stage 3 so a reviewer sees what the blind critique was supposed to find.
    """
    sft = [json.loads(l) for l in (run_dir / "stage_5_sft.jsonl").open()]
    summaries = {r["record_id"]: r.get("change_summary")
                 for r in map(json.loads, (run_dir / "stage_3_perturbed.jsonl").open())}
    out = []
    for r in sft:
        md = dict(r["metadata"])
        md["split"] = md["cell"]
        md["category"] = md["trait_name"]
        if summaries.get(md["record_id"]):
            md["change_summary"] = summaries[md["record_id"]]
        out.append({"id": md["record_id"], "messages": r["messages"], "metadata": md})
    return out


def _stats(records: list[dict]) -> dict:
    """Mirror the dashboard indexer's datasetStats over the records."""
    roles: dict[str, int] = {}
    splits: dict[str, int] = {}
    cats: dict[str, int] = {}
    turns = []
    for r in records:
        turns.append(len(r["messages"]))
        for m in r["messages"]:
            roles[m["role"]] = roles.get(m["role"], 0) + 1
        splits[r["metadata"]["split"]] = splits.get(r["metadata"]["split"], 0) + 1
        cats[r["metadata"]["category"]] = cats.get(r["metadata"]["category"], 0) + 1
    return {"average_turns": round(sum(turns) / len(turns), 1),
            "role_counts": roles, "splits": splits, "categories": cats}


def _card(run_dir: Path, repo: str, records: list[dict], run_meta: dict) -> str:
    """The dataset card, with every field CLAUDE.md requires stated explicitly."""
    cells = sorted({r["metadata"]["cell"] for r in records})
    return f"""---
license: mit
---

# {repo.split('/')[-1]}

| field | value |
|---|---|
| `experiment` | 15-document human-verification batch of the model-eval-model document type (3 per cell), generated by the real pipeline ahead of the full 2,100-doc corpus for the 20/80-by-examples SFT run. |
| `date_generated` | 2026-08-05 |
| `constitution` | `claude_distilled_09_principles_mid_20260804` — the 9-principle generation-time snapshot (sha256 `fe2ed960…`), byte-exact match of the constitution the source difficult-advice corpus was generated against; in the source repo under `constitutions/claude_distilled_09_principles_mid_20260804/`. |
| `source_repo` | https://github.com/Matthew-Bozoukov/teaching_claude_why_replication @ `{run_meta.get('git_sha', 'unknown')}` |
| `models` | `anthropic/claude-sonnet-5` (all four generation call sites: control / critique / reflect / perturb, via OpenRouter) |
| `generation_config` | seed 0; control t=0.7 max_tokens=8192; critique/reflect t=0.8 max_tokens=12288; perturb t=0.7 max_tokens=8192; explicitness name/paraphrase/embody 0.3/0.4/0.3; flaw grid omission/commission/miscalibration/over_application × clear/moderate/grey. |
| `schema` | `id` = record_id (`<scenario_id>::<cell>`); `messages` = the training conversation (assistant turns may carry `reasoning_content` — the private deliberation); `metadata` = cell, attribution, response_kind, flaw_type/severity, explicitness, verdict, trait, supervise, plus browser projections `split`=cell, `category`=trait_name and (flawed cells) `change_summary` = the planted flaw, metadata-only, never trains. |
| `provenance` | `uv run scripts/data/synthdoc/build_dataset.py --config configs/data/synthdoc/model_eval_model.yaml --overrides "cells.control=3,cells.m4_other_good=3,cells.m3_other_flawed=3,cells.m2_self_good=3,cells.m1_self_flawed=3"` (source corpus `LASR-Callum/synthdoc-v2-difficult-advice`, run `{run_dir.name}`). |

Cells: {', '.join(cells)}. Validity checks (`synthdoc check`) all pass; note the
flaw-identification probe at this n: 1/4 `clear` hits — the review question is whether
perturbations are too subtle or critiques too charitable. `supervise` in metadata marks
which assistant turns train (`final` for the self cells).
"""


def main(run_dir: str, repo: str, dry_run: bool = True) -> None:
    """Publish one run dir to HF in the dashboard layout; dry-runs by default."""
    assert re.match(r"^[\w-]+/\d{4}-\d{2}-\d{2}-[a-z0-9-]+$", repo), (
        f"repo {repo!r} must be <org>/<YYYY-MM-DD>-<short-description>")
    load_dotenv()
    d = Path(run_dir)
    records = _records(d)
    run_meta = json.loads((d / "manifest.json").read_text())

    stage = d / "hf_dashboard"
    (stage / "chunks").mkdir(parents=True, exist_ok=True)
    (stage / "data").mkdir(exist_ok=True)

    (stage / "data" / "dialogues.jsonl").write_text(
        "".join(json.dumps(r, ensure_ascii=False) + "\n" for r in records))
    chunks = []
    for i in range(0, len(records), CHUNK_SIZE):
        name = f"chunks/chunk-{i // CHUNK_SIZE:03d}.json"
        (stage / name).write_text(json.dumps(records[i:i + CHUNK_SIZE]) + "\n")
        chunks.append(name)

    manifest = {
        "dataset": {
            "source_file": "data/dialogues.jsonl",
            "format": "jsonl",
            "record_count": len(records),
            "chunk_size": CHUNK_SIZE,
            "chunks": chunks,
            "stats": _stats(records),
            "total_bytes": sum(p.stat().st_size for p in (stage / "chunks").iterdir()),
        },
        "field_mapping": {"id": "metadata.record_id", "split": "metadata.cell",
                          "category": "metadata.trait_name"},
        "generating_run": {"run_dir": d.name, "git_sha": run_meta.get("git_sha"),
                           "constitution_sha256": run_meta.get("constitution_sha256")},
    }
    (stage / "manifest.json").write_text(json.dumps(manifest, indent=2))
    (stage / "README.md").write_text(_card(d, repo, records, run_meta))

    files = sorted(p for p in stage.rglob("*") if p.is_file())
    for p in files:
        print(f"  {p.relative_to(stage)}  {p.stat().st_size:,} B")
    if dry_run:
        print(f">>> DRY RUN: staged {len(files)} files in {stage}; pass --dry_run=False to upload to {repo}")
        return

    from huggingface_hub import HfApi
    api = HfApi()
    api.create_repo(repo, repo_type="dataset", exist_ok=True)
    api.upload_folder(folder_path=str(stage), repo_id=repo, repo_type="dataset")
    commit = api.list_repo_commits(repo, repo_type="dataset")[0].commit_id
    print(f">>> uploaded to https://huggingface.co/datasets/{repo}")
    print(f">>> pin this revision in the dashboard entry: {commit}")


if __name__ == "__main__":
    fire.Fire(main)
