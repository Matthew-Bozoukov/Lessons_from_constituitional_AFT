# ABOUTME: Renders one difficult-advice row from the Fig. 2 DA+tools mix (unused tool definitions) as
# ABOUTME: LaTeX in the paper's \exhead + tsystem/ttools/tuser/treasoning/tresponse format.
"""The row is located by its 2026-10-02 corpus scenario and asserted identical to the default DA
example (system, user, reasoning, response), so the only addition on show is the tool list.

Run: uv run python scratch/da_tools_latex_20261105.py [scenario_id]   (default r2_t8_b05_s000)
"""
import json
import sys
from datetime import date
from pathlib import Path

from huggingface_hub import hf_hub_download

from cot_variant_latex_20261105 import SYNTH, TOKEN, env, tex  # sibling scratch script

# Mixture the Fig. 2 adapter dougalldeepmind/2026-10-11-qwen36-0-da-tools-15 trained on.
MIX = ("dougalldeepmind/2026-10-11-da-tools-15-mix", "da195751376fea70439730adda75a516aa5bc688")
SCENARIO = sys.argv[1] if len(sys.argv) > 1 else "r2_t8_b05_s000"
OUT = Path("output/latex") / f"{date.today().isoformat()}_da_tools_example_{SCENARIO}.tex"


def jsonl(repo: str, rev: str, file: str) -> list[dict]:
    path = hf_hub_download(repo, file, repo_type="dataset", revision=rev, token=TOKEN)
    return [json.loads(line) for line in open(path, encoding="utf-8")]


def tools_json(tools: list[dict]) -> str:
    """Pretty JSON with each parameter's spec on one line, the paper's listing style."""
    out = ["["]
    for k, t in enumerate(tools):
        f, p = t["function"], t["function"]["parameters"]
        props = list(p["properties"].items())
        assert set(t) == {"type", "function"} and set(f) == {"name", "description", "parameters"}, t
        assert set(p) == {"properties", "required", "type"}, p
        out += ["  {", f'    "type": {json.dumps(t["type"])},', '    "function": {',
                f'      "name": {json.dumps(f["name"])},',
                f'      "description": {json.dumps(f["description"])},',
                '      "parameters": {', '        "properties": {']
        out += [f"          {json.dumps(n)}: {json.dumps(s)}" + ("," if i < len(props) - 1 else "")
                for i, (n, s) in enumerate(props)]
        out += ["        },", f'        "required": {json.dumps(p["required"])},',
                f'        "type": {json.dumps(p["type"])}', "      }", "    }",
                "  }" + ("," if k < len(tools) - 1 else "")]
    out.append("]")
    s = "\n".join(out)
    assert json.loads(s) == tools, "reformatted listing does not round-trip to the row's tools"
    assert all(ord(c) < 128 for c in s), "listings cannot typeset non-ASCII"
    return s


def main() -> None:
    corpus = jsonl(*SYNTH, "dataset.jsonl")
    hits = [(i, r) for i, r in enumerate(corpus) if SCENARIO in json.dumps(r["metadata"])]
    assert len(hits) == 1, f"{SCENARIO}: expected one corpus row, got {len(hits)}"
    c = hits[0][1]["messages"]
    user_turn = next(m["content"] for m in c if m["role"] == "user")

    rows = [(i, r) for i, r in enumerate(jsonl(*MIX, "mixture.jsonl"))
            if r["source"] == "da" and r["messages"][1]["content"] == user_turn]
    assert len(rows) == 1, f"{SCENARIO}: expected one mix row, got {len(rows)}"
    idx, r = rows[0]
    sys_, user, asst = r["messages"]
    # Identical to the default DA example apart from the tools, and trained the default way.
    assert sys_["content"] == c[0]["content"] and asst["content"] == c[-1]["content"]
    assert asst["reasoning_content"] == c[-1]["reasoning_content"] and "supervise" not in r
    assert r["tools"], "row carries no tool definitions"

    scen = SCENARIO.replace("_", r"\_")
    out = [
        f"% Generated by scratch/da_tools_latex_20261105.py -- {SCENARIO} as it appears in the DA+tools",
        f"% mix {MIX[0]} @ {MIX[1][:8]} (row {idx}, 0-based line of mixture.jsonl). System, user,",
        "% reasoning and response are asserted identical to the default example",
        f"% ({SYNTH[0]} @ {SYNTH[1][:7]}); the tools are defined but never called. Needs listings.",
        rf"\exhead{{Unused tool definitions}}{{\texttt{{{MIX[0]}}} @ \texttt{{{MIX[1][:7]}}}, row {idx},"
        rf" scenario \texttt{{{scen}}}}}",
        env("tsystem", tex(sys_["content"])),
        env("ttools", env("lstlisting", tools_json(r["tools"])).rstrip("\n")),
        env("tuser", tex(user["content"])),
        env("treasoning", tex(asst["reasoning_content"])),
        env("tresponse", tex(asst["content"])),
    ]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(out), encoding="utf-8")
    print(OUT)


if __name__ == "__main__":
    main()
