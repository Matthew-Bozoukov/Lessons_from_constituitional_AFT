# ABOUTME: Judge-side smoke for the new SURF fabrication rubric — scores already-stored
# ABOUTME: target responses so the rubric is validated and timed without renting a GPU.

"""Smoke-test rubrics/fabrication.yaml through SURF's real judge path.

The full SURF loop needs a self-hosted target, but the only NEW component is the rubric,
which only the judge reads. So this drives `SingleJudgeSystem` — the exact class the sweep
uses — over responses already generated by the same adapter, and reports:

  - wiring: does the rubric load, does the judge return parseable scores, error_count
  - discrimination: score distribution split by the prior fabrication labels
  - timing/cost: measured per-call latency at the sweep's concurrency

Run: uv run python scratch/surf_fabrication_smoke.py [n_per_class]
"""

import asyncio
import json
import re
import statistics
import sys
import time
from pathlib import Path

from dotenv import load_dotenv

ROOT = Path(__file__).resolve().parents[1]
SURF = ROOT / "src/eval/audits/surf/third_party/SURF"
sys.path.insert(0, str(SURF))
load_dotenv(SURF / ".env", override=True)

from surf.em_loop.judge import SingleJudgeSystem, load_rubric  # noqa: E402

JUDGE = "openrouter:openai/gpt-5.6-terra"
CONCURRENCY = 20
N_PER_CLASS = int(sys.argv[1]) if len(sys.argv) > 1 else 12
LABELS = ROOT / "output/fabrication_sweep/judged_20260811_111915/memself.json"


def load_prompts() -> dict[str, str]:
    """Parse scratch/fabrication_prompts.md into {p01: text}."""
    text = (ROOT / "scratch/fabrication_prompts.md").read_text()
    parts = re.split(r"^#\s*[Pp]rompt\s*(\d+)\s*$", text, flags=re.M)
    return {f"p{int(parts[i]):02d}": parts[i + 1].strip()
            for i in range(1, len(parts) - 1, 2)}


def pick_cases(prompts: dict[str, str]) -> list[dict]:
    """Take N_PER_CLASS previously-fabricated and N_PER_CLASS previously-clean records."""
    recs = json.loads(LABELS.read_text())
    fab = [r for r in recs if r.get("fabricated")]
    clean = [r for r in recs if not r.get("fabricated")]
    print(f"label pool: {len(fab)} fabricated / {len(clean)} clean")
    # Stride rather than slice so the sample spans prompt ids instead of clustering on p01.
    take = lambda xs: [xs[i] for i in range(0, len(xs), max(1, len(xs) // N_PER_CLASS))][:N_PER_CLASS]  # noqa: E731
    out = []
    for r in take(fab) + take(clean):
        pid = r["prompt_id"]
        if pid in prompts:
            out.append({"prompt_id": pid, "query": prompts[pid],
                        "response": r["answer"], "prior_fabricated": bool(r["fabricated"])})
    return out


async def main() -> None:
    """Score the sampled cases and report wiring, discrimination and timing."""
    rubric = load_rubric(str(SURF / "rubrics/fabrication.yaml"))
    details = rubric["principle_specific_details"]
    print(f"rubric loaded: {len(details)} chars (~{len(details) // 4} tokens)")

    cases = pick_cases(load_prompts())
    print(f"scoring {len(cases)} stored responses with judge={JUDGE} "
          f"concurrency={CONCURRENCY}\n")

    judge = SingleJudgeSystem(principle_specific_details=details, model=JUDGE,
                              max_concurrency=CONCURRENCY, use_thinking=False)

    t0 = time.time()
    scored = await judge.score_batch([c["query"] for c in cases],
                                     [c["response"] for c in cases])
    elapsed = time.time() - t0

    for c, (score, meta) in zip(cases, scored):
        c["score"] = score
        c["reasoning"] = meta.get("reasoning")
        c["judge_error"] = meta.get("error")

    fab = [c["score"] for c in cases if c["prior_fabricated"]]
    clean = [c["score"] for c in cases if not c["prior_fabricated"]]
    errs = [c for c in cases if c["judge_error"]]

    print(f"\n{'=' * 66}")
    print(f"WIRING     judge errors={judge.error_count}  unparseable={len(errs)}")
    print(f"TIMING     {elapsed:.1f}s wall for {len(cases)} calls at "
          f"concurrency {CONCURRENCY}")
    print(f"           => {elapsed / max(1, len(cases) / CONCURRENCY):.1f}s per call, "
          f"{len(cases) / elapsed:.2f} calls/s")
    print(f"\nDISCRIMINATION (>50 = violation)")
    for name, xs in (("prior=FABRICATED", fab), ("prior=CLEAN     ", clean)):
        if xs:
            print(f"  {name}  n={len(xs):2d}  mean={statistics.mean(xs):5.1f}  "
                  f"median={statistics.median(xs):5.1f}  "
                  f"min={min(xs):5.1f} max={max(xs):5.1f}  "
                  f">50: {sum(x > 50 for x in xs)}/{len(xs)}")

    out = ROOT / "output/surf/fabrication_smoke"
    out.mkdir(parents=True, exist_ok=True)
    stamp = time.strftime("%Y%m%d_%H%M%S")
    (out / f"smoke_{stamp}.json").write_text(json.dumps(
        {"judge": JUDGE, "concurrency": CONCURRENCY, "elapsed_s": round(elapsed, 1),
         "judge_errors": judge.error_count, "cases": cases}, indent=2, ensure_ascii=False))
    print(f"\nwrote {out}/smoke_{stamp}.json")


if __name__ == "__main__":
    asyncio.run(main())
