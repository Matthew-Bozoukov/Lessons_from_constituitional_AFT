# ABOUTME: Renders one row of a pinned DA-family training mixture (low stakes, amoral) as LaTeX in the
# ABOUTME: paper's \exhead + tsystem/tuser/treasoning/tresponse format, checked verbatim against its corpus.
"""Each preset is the newest mixture of its kind and the corpus it was built from. The row is asserted
verbatim against its corpus row, so the scenario id in the header is checked, not inferred.

  low     Jamie's da-low (docs/LOG.md 2026-10-04): da.yaml with three sentences changed to keep the
          stakes low; trained by dougalldeepmind/2026-10-06-qwen36-0-da-low-15.
  amoral  Nika's da-amoral (docs/LOG.md 2026-11-03): the morally neutral twin of difficult advice;
          trained by dougalldeepmind/2026-11-03-qwen36-0-da-amoral-15.

Run: uv run python scratch/mix_example_latex_20261105.py {low,amoral} [mix_row]
"""
import json
import re
import sys
from datetime import date
from pathlib import Path

from huggingface_hub import hf_hub_download

from cot_variant_latex_20261105 import TOKEN, env, tex  # sibling scratch script

PRESETS = {  # title, mix (repo, rev), corpus (repo, rev), source key, default row
    "low": ("Low stakes",
            ("dougalldeepmind/2026-10-06-da-low-15-mix", "43e365603a113f159de0e11df75e64b01f7583da"),
            ("dougalldeepmind/2026-10-04-da-low-synth", "c8a61e2661be8d564b27bfb513ba3f31eec27897"),
            "da-low", 50),
    "amoral": ("Amoral",
               ("dougalldeepmind/2026-11-03-da-amoral-15-mix", "1b98495469696c87e1c4863661a4c186be0734a4"),
               ("dougalldeepmind/2026-11-03-da-amoral-synth", "ac8e1efe10611b1f43c8d58110b7a53b670fae52"),
               "da-amoral", 60),
}


def jsonl(repo: str, rev: str, file: str) -> list[dict]:
    path = hf_hub_download(repo, file, repo_type="dataset", revision=rev, token=TOKEN)
    return [json.loads(line) for line in open(path, encoding="utf-8")]


def body(s: str) -> str:
    """tex(), plus the corpora's markdown: **bold**, *emphasis*, and `- ` / `1. ` lists."""
    s = re.sub(r"\*\*([^*\n]+)\*\*", r"\\textbf{\1}", tex(s))
    s = re.sub(r"\*([^*\n]+)\*", r"\\emph{\1}", s)
    out, kind = [], None
    for line in s.split("\n"):
        m = re.match(r"^(?:(- )|(\d+)\. )(.*)$", line)
        new = ("itemize" if m.group(1) else "enumerate") if m else None
        if kind and new != kind and line.strip():   # a blank line inside a list does not end it
            out.append(f"\\end{{{kind}}}")
            kind = None
        if new and not kind:
            out.append(f"\\begin{{{new}}}")
            kind = new
        out.append(f"\\item {m.group(3)}" if m else line)
    if kind:
        out.append(f"\\end{{{kind}}}")
    s = "\n".join(out)
    assert "*" not in s, "unconverted markdown asterisk"
    return s


def main() -> None:
    preset = sys.argv[1]
    title, mix, corpus, source, row = PRESETS[preset]
    row = int(sys.argv[2]) if len(sys.argv) > 2 else row
    r = jsonl(*mix, "mixture.jsonl")[row]
    assert r["source"] == source and "supervise" not in r and "tools" not in r, (r["source"], r.keys())
    sys_, user, asst = r["messages"]
    hits = [c for c in jsonl(*corpus, "dataset.jsonl")
            if next(m["content"] for m in c["messages"] if m["role"] == "user") == user["content"]]
    assert len(hits) == 1, f"row {row}: expected one corpus row, got {len(hits)}"
    c = hits[0]
    assert c["messages"][0]["content"] == sys_["content"] and c["messages"][-1]["content"] == asst["content"]
    assert c["messages"][-1]["reasoning_content"] == asst["reasoning_content"]
    scenario = c["metadata"]["scenario_id"]

    out = Path("output/latex") / f"{date.today().isoformat()}_{source}_example_{scenario}.tex"
    scen = scenario.replace("_", r"\_")
    lines = [
        f"% Generated by scratch/mix_example_latex_20261105.py {preset} {row} -- row {row} (0-based line of",
        f"% mixture.jsonl) of {mix[0]} @ {mix[1][:8]}, verbatim from {corpus[0]} @ {corpus[1][:8]}",
        f"% scenario {scenario} (trait {c['metadata']['trait_id']}). Default supervision (reasoning and response both trained).",
        rf"\exhead{{{title}}}{{\texttt{{{mix[0]}}} @ \texttt{{{mix[1][:7]}}}, row {row},"
        rf" scenario \texttt{{{scen}}}}}",
        env("tsystem", body(sys_["content"])),
        env("tuser", body(user["content"])),
        env("treasoning", body(asst["reasoning_content"])),
        env("tresponse", body(asst["content"])),
    ]
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8")
    print(out)


if __name__ == "__main__":
    main()
